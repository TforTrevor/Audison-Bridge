"""Embed the offline dashboard in ESP32 flash. No third-party dependencies."""
from pathlib import Path
import argparse

root = Path(__file__).resolve().parents[1]
source = root / "dashboard" / "index.html"
target = root / "HyundaiAudisonBridge" / "Dashboard.h"
html = source.read_text(encoding="utf-8")
assert ')BRIDGEPAGE"' not in html
content = ('// Generated by tools/embed_dashboard.py; edit dashboard/index.html.\n'
           '#pragma once\n#include <pgmspace.h>\n'
           'static const char DASHBOARD_HTML[] PROGMEM = R"BRIDGEPAGE(' + html + ')BRIDGEPAGE";\n')
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        raise SystemExit("Dashboard.h is stale: run python tools/embed_dashboard.py")
    print("PASS: embedded dashboard matches its source")
else:
    target.write_text(content, encoding="utf-8", newline="\n")
    print(f"Embedded {len(html.encode('utf-8')):,} bytes into {target}")
